-- ----------------------------------------------------------------------------
-- 1. Table: daily_bookings
-- Tracks actual lodge bookings, rooms sold, and price charged.
-- Stored generated column 'revenue' automatically calculates total revenue.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS daily_bookings (
  stay_date    DATE PRIMARY KEY,
  rooms_booked INT NOT NULL CHECK (rooms_booked BETWEEN 0 AND 20),
  price        INT NOT NULL,                                     -- price per room (Rs. 2,000 to 9,000)
  revenue      INT GENERATED ALWAYS AS (rooms_booked * price) STORED,
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 2. Table: price_recommendations
-- Stores daily recommendations generated by the AI dynamic pricing engine.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS price_recommendations (
  stay_date         DATE PRIMARY KEY,
  recommended_price INT NOT NULL,
  occupancy_pct     DECIMAL(5,1) NOT NULL,
  expected_revenue  INT NOT NULL,
  generated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 3. Table: users
-- Stores owner and administrator authentication credentials with hashed passwords.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  username      VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(20) NOT NULL DEFAULT 'owner'
);

-- ----------------------------------------------------------------------------
-- 4. Table: owner_feedback
-- Stores owner feedback, observations, accuracy ratings, and feature requests.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS owner_feedback (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  category   VARCHAR(100) NOT NULL,
  rating     INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment    TEXT NOT NULL,
  author     VARCHAR(50) NOT NULL DEFAULT 'owner',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

